#!/usr/bin/env node
/* Publishes the framework's browser files into the site (docs/ is deployed as-is):

     docs/assets/framework/archive-ledger.js   framework/ledger.js + framework/adapters/track.js
     docs/assets/framework/sequence-engine.js  framework/engine/sequence-engine.js
     docs/assets/framework/ritual-player.js    framework/ui/ritual-player.js
     docs/assets/framework/rituals/<slug>.json every ritual in data/rituals/ whose review status is
                                               "pending" or "cleared" (drafts are never published)
     docs/assets/framework/rituals/index.json  which museum room (lectern) or object (case) offers which walkthrough

   The framework/ files are the source; never edit the copies.
   Usage: node tools/build-framework.js [--check] */
"use strict";
const fs = require("fs");
const path = require("path");

const ROOT = path.join(__dirname, "..");
const OUT = path.join(ROOT, "docs", "assets", "framework");
const read = (p) => fs.readFileSync(path.join(ROOT, p), "utf8");
const banner = (src) => "/* Generated by tools/build-framework.js from " + src + "; do not edit this copy. */\n";

const out = {};
out["archive-ledger.js"] = banner("framework/ledger.js and framework/adapters/track.js") + read("framework/ledger.js") + "\n" + read("framework/adapters/track.js");
out["sequence-engine.js"] = banner("framework/engine/sequence-engine.js") + read("framework/engine/sequence-engine.js");
out["ritual-player.js"] = banner("framework/ui/ritual-player.js") + read("framework/ui/ritual-player.js");

const index = { note: "Generated by tools/build-framework.js. Only rituals under review or cleared are published; drafts are not.", rooms: {}, rituals: {} };
const ritDir = path.join(ROOT, "data", "rituals");
for (const f of fs.readdirSync(ritDir).filter((f) => f.endsWith(".json")).sort()) {
  const r = JSON.parse(fs.readFileSync(path.join(ritDir, f), "utf8"));
  const status = r.review && r.review.status;
  if (status !== "pending" && status !== "cleared") continue;
  // tier 1, or tier 2 with Carter's recorded approval of the framing (framing_approval); tier 3 never
  if (!(r.sensitivity_tier === 1 || (r.sensitivity_tier === 2 && r.framing_approval && r.framing_approval.by === "Carter"))) throw new Error(f + ": only tier-1 walkthroughs, or tier-2 ones with Carter's recorded framing approval, may be published");
  const slug = f.slice(0, -5);
  out["rituals/" + f] = JSON.stringify(r) + "\n";
  index.rituals[slug] = { title: r.title, status, chapter: r.chapter || null };
  // a walkthrough tied to a museum object is launched from that object's case, not the lectern
  if (r.museum_object) {
    const obj = r.museum_object.replace(/^relic:/, "");
    index.rituals[slug].object = obj;
    (index.objects = index.objects || {})[obj] = slug;
  } else if (r.chapter) {
    const room = r.chapter.replace(/^chapter:/, "");
    (index.rooms[room] = index.rooms[room] || []).push(slug);
  }
}
out["rituals/index.json"] = JSON.stringify(index) + "\n";

const existing = [];
const walk = (d, pre) => { if (!fs.existsSync(d)) return; for (const e of fs.readdirSync(d, { withFileTypes: true })) { if (e.isDirectory()) walk(path.join(d, e.name), pre + e.name + "/"); else existing.push(pre + e.name); } };
walk(OUT, "");

if (process.argv.includes("--check")) {
  let bad = 0;
  for (const [f, body] of Object.entries(out)) {
    const p = path.join(OUT, f);
    if (!fs.existsSync(p) || fs.readFileSync(p, "utf8") !== body) { console.error("out of date: docs/assets/framework/" + f); bad++; }
  }
  for (const f of existing) if (!out[f]) { console.error("stale: docs/assets/framework/" + f); bad++; }
  if (bad) { console.error("Run: node tools/build-framework.js"); process.exit(1); }
  console.log("framework files up to date (" + Object.keys(out).length + ")");
} else {
  for (const f of existing) if (!out[f]) fs.unlinkSync(path.join(OUT, f));
  for (const [f, body] of Object.entries(out)) { fs.mkdirSync(path.dirname(path.join(OUT, f)), { recursive: true }); fs.writeFileSync(path.join(OUT, f), body); }
  console.log("framework: wrote " + Object.keys(out).length + " files to docs/assets/framework/ (" + Object.keys(index.rituals).length + " published walkthrough(s))");
}
